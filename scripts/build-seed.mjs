#!/usr/bin/env node
// Builds supabase/seed.sql from supabase/seed/catalog.mjs.
// Deterministic: running it twice produces the same file (seeded random numbers).
// Usage: npm run db:seed:build

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as catalog from "../supabase/seed/catalog.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// ---------- helpers ----------
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replaceAll("'", "''")}'`);
const id = (kind, key) => `md5(${q(`kairo:${kind}:${key}`)})::uuid`;
const paise = (rupees) => Math.round(rupees * 100);

function rng(seed) {
  // mulberry32: tiny, fast, deterministic
  let t = seed >>> 0;
  return () => {
    t = (t + 0x6d2b79f5) >>> 0;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(20261028);
const between = (min, max) => min + Math.floor(rand() * (max - min + 1));

const skuPart = (s) => s.replace(/[^A-Za-z0-9]/g, "").slice(0, 4).toUpperCase();

// ---------- build ----------
const out = [];
out.push("-- GENERATED by scripts/build-seed.mjs from supabase/seed/catalog.mjs — do not edit by hand.");
out.push("-- Every review below is a sample (is_sample = true) and shows a visible 'Sample' tag.");

out.push("");

out.push("-- collections");
for (const c of catalog.collections) {
  out.push(
    `insert into public.collections (id, slug, name, tagline, theme, position) values (${id("collection", c.slug)}, ${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${q(c.theme)}, ${c.position});`,
  );
}

out.push("", "-- drops (start relative to when the seed runs)");
for (const d of catalog.drops) {
  out.push(
    `insert into public.drops (id, slug, name, description, starts_at) values (${id("drop", d.slug)}, ${q(d.slug)}, ${q(d.name)}, ${q(d.description)}, date_trunc('hour', now()) + interval '${d.startsInDays} days');`,
  );
}

out.push("", "-- products, images, variants");
for (const p of catalog.products) {
  out.push(
    `insert into public.products (id, slug, name, collection_id, description, fabric, fit, care, price_paise, compare_at_paise, is_published, drop_id) values (` +
      [
        id("product", p.slug),
        q(p.slug),
        q(p.name),
        id("collection", p.collection),
        q(p.description),
        q(p.fabric),
        q(p.fit),
        q(p.care),
        paise(p.price),
        p.compareAt ? paise(p.compareAt) : "null",
        "true",
        p.drop ? id("drop", p.drop) : "null",
      ].join(", ") +
      ");",
  );

  // two images per product: front and detail (files arrive with the photo shoot, Task 13)
  out.push(
    `insert into public.product_images (product_id, path, alt, position) values ` +
      `(${id("product", p.slug)}, ${q(`${p.slug}/1.avif`)}, ${q(`${p.name} in ${p.colours[0]}, front view`)}, 0), ` +
      `(${id("product", p.slug)}, ${q(`${p.slug}/2.avif`)}, ${q(`${p.name}, fabric and detail close-up`)}, 1);`,
  );

  const rows = [];
  let pos = 0;
  for (const colour of p.colours) {
    for (const size of p.sizes) {
      const sku = `KR-${skuPart(p.slug.split("-").map((w) => w[0]).join(""))}${skuPart(p.slug.split("-").at(-1))}-${skuPart(colour)}-${size}`;
      rows.push(`(${id("product", p.slug)}, ${q(size)}, ${q(colour)}, ${q(sku)}, ${between(3, 20)}, ${pos++})`);
    }
  }
  out.push(`insert into public.variants (product_id, size, colour, sku, stock, position) values ${rows.join(", ")};`);
}

out.push("", "-- pairings: complete the look + wear it another way");
for (const [slug, list] of Object.entries(catalog.looks)) {
  list.forEach((other, i) =>
    out.push(
      `insert into public.product_pairings (product_id, paired_product_id, kind, position) values (${id("product", slug)}, ${id("product", other)}, 'look', ${i});`,
    ),
  );
}
for (const [slug, other] of Object.entries(catalog.anotherWay)) {
  out.push(
    `insert into public.product_pairings (product_id, paired_product_id, kind, position) values (${id("product", slug)}, ${id("product", other)}, 'another_way', 0);`,
  );
}

out.push("", "-- coupons (fixed values stored in paise; percent values as a whole number)");
for (const c of catalog.coupons) {
  const value = c.kind === "fixed" ? paise(c.value) : c.value;
  out.push(
    `insert into public.coupons (code, kind, value, min_subtotal_paise, max_uses) values (${q(c.code)}, ${q(c.kind)}, ${value}, ${paise(c.minSubtotal)}, ${c.maxUses ?? "null"});`,
  );
}

out.push("", "-- sample reviews (approved, clearly tagged as samples)");
for (const p of catalog.products) {
  const pool = catalog.sampleReviewText[p.collection];
  const count = between(3, 4);
  const start = between(0, pool.length - 1);
  for (let i = 0; i < count; i++) {
    const r = pool[(start + i) % pool.length];
    const who = catalog.sampleReviewers[between(0, catalog.sampleReviewers.length - 1)];
    const daysAgo = between(3, 120);
    out.push(
      `insert into public.reviews (product_id, author_name, rating, title, body, is_sample, status, created_at) values (${id("product", p.slug)}, ${q(who)}, ${r.rating}, ${q(r.title)}, ${q(r.body)}, true, 'approved', now() - interval '${daysAgo} days');`,
    );
  }
}

out.push("");

const file = path.join(root, "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${path.relative(root, file)}: ${catalog.products.length} products.`);
