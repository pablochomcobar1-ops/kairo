#!/usr/bin/env node
// Generates src/types/db.ts from the linked Supabase project.
// Written as a script (not `> file`) because PowerShell's `>` saves UTF-16,
// which breaks TypeScript. Usage: npm run db:types

import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = spawnSync("npx", ["supabase", "gen", "types", "typescript", "--linked", "--schema", "public"], {
  cwd: root,
  encoding: "utf8",
  shell: process.platform === "win32",
  maxBuffer: 20 * 1024 * 1024,
});

if (result.status !== 0 || !result.stdout.includes("export type")) {
  console.error(result.stderr || "Type generation failed. Did you run `npx supabase link` first?");
  process.exit(1);
}

const out = path.join(root, "src", "types", "db.ts");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `// GENERATED by npm run db:types — do not edit by hand.\n${result.stdout}`, "utf8");
console.log(`Wrote ${path.relative(root, out)}`);
